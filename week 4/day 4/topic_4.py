#Confidence Interval


#A confidence interval gives you a range around your sample estimate.

#instead of saying ! 

#The mean is 50.

#Estimated mean = 50
#Confidence interval = 47 to 53

#That means:

#based on our sample, we think the true population mean is likely somewhere around 47 to 53.

#The key idea is:

#one number
#→ estimate


#range around that number
#→ uncertainty


#A narrow interval means the estimate is more precise.

#49 to 51

#A wide interval means more uncertainty.

#40 to 60


#And this connects directly to standard error:

#smaller standard error
#→ narrower confidence interval


#larger standard error
#→ wider confidence interval